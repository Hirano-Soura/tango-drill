/** @param {Ctx} ctx */
export function render(ctx) {
  ctx.root.innerHTML = `
    ${foldOpen('qa-panel')}
      <summary><h2>よくある質問</h2></summary>
      ${QA.map((g) => `<h3 class="qa-group">${g.title}</h3>
        ${g.items.map(([q, a]) => `<details class="qa"><summary>${q}</summary><p>${a}</p></details>`).join('')}`).join('')}
    </details>
    ${foldOpen('survey-panel')}
      <summary><h2>改善アンケート</h2></summary>
      <p class="hint">不具合の報告や、あったら便利な機能・使いにくい点を教えてください。Google フォームが新しいタブで開きます。
        氏名・学籍番号など、個人を特定できることは書かないでください。</p>
      <div class="rowbtns left"><a class="linkbtn primary" href="${esc(SURVEY_URL)}" target="_blank" rel="noopener noreferrer">アンケートを開く</a></div>
      <p class="hint">回答はフォームに入力した内容だけが Google フォームに送られます。このアプリの単語帳や学習の記録は送られません。</p>
      <p class="meta" id="qa-version">アプリのバージョン: ${esc(VERSION)}(不具合を書くときに添えてください)</p>
    </details>`;
  bindFolds(ctx.root);
}
